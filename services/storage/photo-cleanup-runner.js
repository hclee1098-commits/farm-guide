// ========================================
// 🌱 농사 가이드
// 📸 사진 자동 정리 실행기
// ========================================

// ========================================
// 1. 실행기 생성
// ========================================

function createPhotoCleanupRunner({
  queue,
  deletePhotoFile,
  intervalMs = 60 * 60 * 1000,
}) {
  // ========================================
  // 2. 입력값 검증
  // ========================================

  if (!queue || typeof queue.retryPending !== "function") {
    throw new Error("사진 정리 큐가 올바르지 않습니다.");
  }

  if (typeof deletePhotoFile !== "function") {
    throw new Error("사진 삭제 함수가 올바르지 않습니다.");
  }

  if (!Number.isSafeInteger(intervalMs) || intervalMs <= 0) {
    throw new Error("사진 정리 실행 간격이 올바르지 않습니다.");
  }

  // ========================================
  // 3. 실행 상태
  // ========================================

  let running = false;

  let timer = null;

  // ========================================
  // 4. 정리 작업 1회 실행
  // ========================================

  async function runOnce() {
    // ========================================
    // 동일 실행기 중복 실행 차단
    // ========================================

    if (running) {
      console.log("📸 사진 정리 작업이 이미 실행 중입니다.");

      return {
        skipped: true,
      };
    }

    running = true;

    try {
      console.log("📸 미완료 사진 정리 시작");

      // ========================================
      // 실제 정리 작업
      //
      // 24시간 보호
      // DB 참조 확인
      // 원자적 작업 선점
      // ========================================

      const result = await queue.retryPending(deletePhotoFile);

      console.log("📸 사진 정리 결과:", result);

      return result;
    } finally {
      // ========================================
      // 성공 및 실패 모두 실행 상태 해제
      // ========================================

      running = false;
    }
  }

  // ========================================
  // 5. 자동 실행 시작
  // ========================================

  function start() {
    if (timer !== null) {
      return;
    }

    console.log("📸 사진 자동 정리 실행기 시작");

    // ========================================
    // 자동 실행 중 예외 처리
    // ========================================

    function execute() {
      void runOnce().catch((error) => {
        console.error("📸 사진 자동 정리 실행 오류:", error);
      });
    }

    // ========================================
    // 정기 실행 등록
    // ========================================

    timer = setInterval(execute, intervalMs);

    // 타이머가 서버 종료를 방해하지 않도록 설정
    timer.unref?.();

    // ========================================
    // 서버 시작 직후 1회 실행
    // ========================================

    execute();
  }

  // ========================================
  // 6. 자동 실행 중지
  // ========================================

  function stop() {
    if (timer === null) {
      return;
    }

    clearInterval(timer);

    timer = null;

    console.log("📸 사진 자동 정리 실행기 중지");
  }

  // ========================================
  // 7. 외부 사용 함수
  // ========================================

  return {
    start,
    stop,
    runOnce,
  };
}

module.exports = createPhotoCleanupRunner;
