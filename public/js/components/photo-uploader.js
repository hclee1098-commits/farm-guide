// ========================================
// 🌱 농사 가이드
// 📸 공통 사진 업로드 컴포넌트
// ========================================

// ========================================
// 1. 공통 사진 업로드 컴포넌트 생성
// ========================================

export function createPhotoUploader({
  input,
  preview,

  maxPhotos = 10,

  maxFileSize = 3 * 1024 * 1024,

  allowedTypes = ["image/jpeg", "image/png", "image/webp"],

  getExistingCount = () => 0,

  canSelect = () => true,

  onBlocked = () => {},

  // ========================================
  // 사진 선택 상태 변경 이벤트
  // ========================================

  onChange = () => {},

  // ========================================
  // 내부 상태 안내 표시 여부
  // ========================================

  showSelectionStatus = true,
}) {
  // ========================================
  // 2. 요소 검증
  // ========================================

  if (
    !(input instanceof HTMLInputElement) ||
    !(preview instanceof HTMLElement)
  ) {
    throw new Error("사진 업로드 컴포넌트 요소가 올바르지 않습니다.");
  }

  // ========================================
  // 3. 내부 상태
  // ========================================

  let selectedFiles = [];

  let previewUrls = [];

  let destroyed = false;

  // ========================================
  // 4. 사진 입력 설정
  // ========================================

  input.multiple = true;

  input.accept = allowedTypes.join(",");

  // ========================================
  // 5. 슬라이더 확인
  // ========================================

  const slider = preview.closest(".diary-slider");

  // ========================================
  // 6. 선택 상태 안내 영역
  // ========================================

  let status = null;

  // ========================================
  // 내부 상태 안내를 사용하는 경우
  // ========================================

  if (showSelectionStatus) {
    status = document.createElement("p");

    status.className = "diary-photo-selection-status";

    status.setAttribute("role", "status");

    status.setAttribute("aria-live", "polite");

    status.hidden = true;

    // ========================================
    // 미리보기 위에 상태 안내 배치
    // ========================================

    if (slider) {
      slider.before(status);
    } else {
      preview.before(status);
    }
  }

  // ========================================
  // 7. 사진 선택 상태 변경 알림
  // ========================================

  function notifyChange() {
    if (destroyed) {
      return;
    }

    // ========================================
    // 현재 선택된 사진 목록 복사
    // ========================================

    const files = [...selectedFiles];

    // ========================================
    // 외부 컴포넌트에 상태 전달
    // ========================================

    onChange({
      files,

      count: files.length,
    });
  }

  // ========================================
  // 8. 임시 사진 URL 정리
  // ========================================

  function clearPreviewUrls() {
    previewUrls.forEach((url) => {
      URL.revokeObjectURL(url);
    });

    previewUrls = [];
  }

  // ========================================
  // 9. 사진 중복 확인
  // ========================================

  function isSameFile(a, b) {
    return (
      a.name === b.name &&
      a.size === b.size &&
      a.lastModified === b.lastModified
    );
  }

  // ========================================
  // 10. 사진 형식 및 용량 검사
  // ========================================

  function validateFile(file) {
    // ========================================
    // 사진 형식 검사
    // ========================================

    if (!allowedTypes.includes(file.type)) {
      throw new Error(
        `${file.name}\n\n` + "JPG, PNG, WebP 사진만 등록할 수 있습니다.",
      );
    }

    // ========================================
    // 빈 파일 검사
    // ========================================

    if (file.size === 0) {
      throw new Error(
        `${file.name}\n\n` + "내용이 없는 사진은 등록할 수 없습니다.",
      );
    }

    // ========================================
    // 사진 크기 검사
    // ========================================

    if (file.size > maxFileSize) {
      const maxMB = maxFileSize / (1024 * 1024);

      throw new Error(
        `${file.name}\n\n` + `사진 한 장의 크기는 최대 ${maxMB}MB입니다.`,
      );
    }
  }

  // ========================================
  // 11. 내부 선택 상태 안내 갱신
  // ========================================

  function updateStatus() {
    // ========================================
    // 내부 안내를 사용하지 않는 경우
    // ========================================

    if (!status) {
      return;
    }

    const count = selectedFiles.length;

    // ========================================
    // 선택한 사진이 없는 경우
    // ========================================

    if (count === 0) {
      status.hidden = true;

      status.textContent = "";

      return;
    }

    // ========================================
    // 선택한 사진이 있는 경우
    // ========================================

    status.hidden = false;

    status.textContent =
      `📸 새로 추가할 사진: ${count}장\n` +
      "⚠️ 아직 저장되지 않았습니다. " +
      "아래 저장 버튼을 누르면 등록됩니다.";
  }

  // ========================================
  // 12. 사진 미리보기 표시
  // ========================================

  function render() {
    if (destroyed) {
      return;
    }

    // ========================================
    // 기존 임시 URL 정리
    // ========================================

    clearPreviewUrls();

    // ========================================
    // 기존 미리보기 제거
    // ========================================

    preview.replaceChildren();

    // ========================================
    // 선택한 사진이 없는 경우
    // ========================================

    if (selectedFiles.length === 0) {
      preview.hidden = true;

      if (slider) {
        slider.hidden = true;
      }

      // ========================================
      // 내부 상태 안내 갱신
      // ========================================

      updateStatus();

      return;
    }

    // ========================================
    // 미리보기 표시
    // ========================================

    preview.hidden = false;

    if (slider) {
      slider.hidden = false;
    }

    // ========================================
    // 사진 카드 생성
    // ========================================

    selectedFiles.forEach((file, index) => {
      const item = document.createElement("div");

      item.className = "diary-photo-preview-item";

      // ========================================
      // 사진 이미지
      // ========================================

      const image = document.createElement("img");

      image.className = "diary-photo-preview-image";

      // ========================================
      // 임시 이미지 URL 생성
      // ========================================

      const imageUrl = URL.createObjectURL(file);

      previewUrls.push(imageUrl);

      image.src = imageUrl;

      image.alt = file.name;

      image.draggable = false;

      // ========================================
      // 사진 선택 취소 버튼
      // ========================================

      const removeBtn = document.createElement("button");

      removeBtn.type = "button";

      removeBtn.className = "diary-photo-remove-btn";

      removeBtn.textContent = "✕";

      removeBtn.setAttribute("aria-label", `${file.name} 선택 취소`);

      // ========================================
      // 사진 선택 취소
      // ========================================

      removeBtn.addEventListener("click", () => {
        // ========================================
        // 컴포넌트 종료 확인
        // ========================================

        if (destroyed) {
          return;
        }

        // ========================================
        // 사진 변경 가능 여부
        // ========================================

        if (!canSelect()) {
          onBlocked();

          return;
        }

        // ========================================
        // 선택한 사진 제거
        // ========================================

        selectedFiles.splice(index, 1);

        // ========================================
        // 미리보기 갱신
        // ========================================

        render();

        // ========================================
        // 사진 변경 상태 알림
        // ========================================

        notifyChange();
      });

      // ========================================
      // 파일 이름
      // ========================================

      const fileName = document.createElement("span");

      fileName.className = "diary-photo-file-name";

      fileName.textContent = file.name;

      // ========================================
      // 사진 카드 완성
      // ========================================

      item.append(image, removeBtn, fileName);

      preview.appendChild(item);
    });

    // ========================================
    // 내부 상태 안내 갱신
    // ========================================

    updateStatus();

    // ========================================
    // 슬라이더 버튼 상태 갱신
    // ========================================

    requestAnimationFrame(() => {
      if (!destroyed && preview.isConnected && !preview.hidden) {
        preview.dispatchEvent(new Event("scroll"));
      }
    });
  }

  // ========================================
  // 13. 사진 선택 처리
  // ========================================

  function handleFileChange() {
    if (destroyed) {
      return;
    }

    // ========================================
    // 선택한 파일 목록
    // ========================================

    const files = Array.from(input.files || []);

    // ========================================
    // 같은 파일 다시 선택 가능
    // ========================================

    input.value = "";

    // ========================================
    // 사진 선택 가능 여부
    // ========================================

    if (!canSelect()) {
      onBlocked();

      return;
    }

    // ========================================
    // 선택한 파일이 없는 경우
    // ========================================

    if (files.length === 0) {
      return;
    }

    try {
      // ========================================
      // 사진 형식 및 크기 검증
      // ========================================

      files.forEach(validateFile);

      // ========================================
      // 중복 사진 제외
      // ========================================

      const newFiles = [];

      for (const file of files) {
        const alreadySelected = selectedFiles.some((selected) =>
          isSameFile(selected, file),
        );

        const alreadyAdded = newFiles.some((selected) =>
          isSameFile(selected, file),
        );

        if (!alreadySelected && !alreadyAdded) {
          newFiles.push(file);
        }
      }

      // ========================================
      // 새로 추가할 사진이 없는 경우
      // ========================================

      if (newFiles.length === 0) {
        return;
      }

      // ========================================
      // 기존 등록 사진 개수 확인
      // ========================================

      const existingCount = Number(getExistingCount());

      if (!Number.isSafeInteger(existingCount) || existingCount < 0) {
        throw new Error("기존 사진 개수를 확인할 수 없습니다.");
      }

      // ========================================
      // 최대 사진 개수 검사
      // ========================================

      const newCount = selectedFiles.length + newFiles.length;

      const totalCount = existingCount + newCount;

      if (totalCount > maxPhotos) {
        throw new Error(
          `현재 등록된 사진: ${existingCount}장\n` +
            `새로 선택한 사진: ${newCount}장\n\n` +
            `사진은 최대 ${maxPhotos}장까지 등록할 수 있습니다.`,
        );
      }

      // ========================================
      // 선택한 사진 추가
      // ========================================

      selectedFiles.push(...newFiles);

      // ========================================
      // 미리보기 갱신
      // ========================================

      render();

      // ========================================
      // 사진 변경 상태 알림
      // ========================================

      notifyChange();

      console.log("📸 사진 선택 완료:", selectedFiles.length);
    } catch (error) {
      console.error("사진 선택 오류:", error);

      alert(error.message);
    }
  }

  // ========================================
  // 14. 사진 선택 이벤트
  // ========================================

  input.addEventListener("change", handleFileChange);

  // ========================================
  // 15. 선택한 사진 목록 반환
  // ========================================

  function getFiles() {
    return [...selectedFiles];
  }

  // ========================================
  // 16. 선택한 사진 개수
  // ========================================

  function getCount() {
    return selectedFiles.length;
  }

  // ========================================
  // 17. 사진 선택 초기화
  // ========================================

  function reset() {
    if (destroyed) {
      return;
    }

    // ========================================
    // 선택 사진 초기화
    // ========================================

    selectedFiles = [];

    // ========================================
    // 파일 입력 초기화
    // ========================================

    input.value = "";

    // ========================================
    // 미리보기 초기화
    // ========================================

    render();

    // ========================================
    // 사진 변경 상태 알림
    // ========================================

    notifyChange();
  }

  // ========================================
  // 18. 컴포넌트 정리
  // ========================================

  function destroy() {
    if (destroyed) {
      return;
    }

    // ========================================
    // 컴포넌트 종료 상태
    // ========================================

    destroyed = true;

    // ========================================
    // 이벤트 제거
    // ========================================

    input.removeEventListener("change", handleFileChange);

    // ========================================
    // 임시 이미지 URL 정리
    // ========================================

    clearPreviewUrls();

    // ========================================
    // 선택 사진 초기화
    // ========================================

    selectedFiles = [];

    input.value = "";

    // ========================================
    // 미리보기 제거
    // ========================================

    preview.replaceChildren();

    preview.hidden = true;

    if (slider) {
      slider.hidden = true;
    }

    // ========================================
    // 내부 상태 안내 제거
    // ========================================

    status?.remove();

    status = null;
  }

  // ========================================
  // 19. 초기 화면 설정
  // ========================================

  // 초기 생성 시에는 onChange를 실행하지 않는다.
  // 외부 상태 컴포넌트가 아직 생성되지 않았을 수 있다.

  render();

  // ========================================
  // 20. 외부에서 사용할 함수
  // ========================================

  return {
    getFiles,

    getCount,

    reset,

    destroy,
  };
}
