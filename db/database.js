// ========================================
// 🌱 농사 가이드 데이터베이스 연결 관리
// ========================================

// ========================================
// 1. 모듈 불러오기
// ========================================

const { DatabaseSync } = require("node:sqlite");

const path = require("path");

// ========================================
// 2. 데이터베이스 파일 경로
// ========================================

// 기존 farm-guide.db 파일을 그대로 사용
const DB_PATH = path.join(__dirname, "..", "farm-guide.db");

// ========================================
// 3. SQLite 데이터베이스 연결
// ========================================

console.log("==============================");
console.log("🌱 데이터베이스 연결 시작");
console.log("==============================");

const db = new DatabaseSync(DB_PATH);

// ========================================
// 4. SQLite 외래 키 제약 조건 활성화
// ========================================

db.exec("PRAGMA foreign_keys = ON");

// ========================================
// 5. 데이터베이스 연결 확인
// ========================================

console.log("SQLite 외래 키 활성화 완료!");

console.log("데이터베이스 연결 성공!");

console.log("==============================");

// ========================================
// 6. 데이터베이스 객체 내보내기
// ========================================

module.exports = db;
